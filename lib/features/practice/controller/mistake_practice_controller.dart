import 'package:flutter/widgets.dart';
import 'package:get/get.dart';

import '../../typing_test/model/typing_language.dart';
import '../../typing_test/model/typing_snapshot.dart';
import '../../typing_test/model/typing_test_status.dart';
import '../../typing_test/model/typing_word_status.dart';
import '../../typing_test/service/typing_engine.dart';
import '../../settings/controller/settings_controller.dart';
import '../../typing_test/service/engine_clock.dart';
import '../../typing_test/service/typing_input.dart';
import '../model/mistake_practice_args.dart';
import '../model/practice_mode.dart';

enum MistakePracticePhase { practice, result }

/// Drives a single practice attempt for any of the five modes. The
/// content was already generated by PracticeController before navigating
/// here — this controller only ever talks to TypingEngine, exactly like
/// every other typing screen in the app. Untimed, like Lessons: the
/// attempt ends when the drill text is finished.
class MistakePracticeController extends GetxController {
  final FocusNode focusNode = FocusNode();

  late final MistakePracticeArgs args;

  final Rx<MistakePracticePhase> phase = MistakePracticePhase.practice.obs;

  @override
  void onInit() {
    super.onInit();
    final Object? raw = Get.arguments;
    if (raw is MistakePracticeArgs) {
      args = raw;
    } else {
      args = const MistakePracticeArgs(
        language: TypingLanguage.english,
        mode: PracticeMode.general,
        content: 'the quick brown fox jumps over the lazy dog',
        practicedCharacters: [],
      );
    }
    _start();
  }

  TypingEngine? _engine;

  TypingEngine get engine {
    final TypingEngine? e = _engine;
    if (e == null) {
      throw StateError('TypingEngine accessed before practice started');
    }
    return e;
  }

  late final EngineClock _clock =
      EngineClock((Duration delta) => _engine?.advanceTime(delta));

  final Rx<TypingSnapshot> snapshot = TypingSnapshot.initial().obs;
  final RxList<TypingWordStatus> wordStatuses = <TypingWordStatus>[].obs;
  final RxList<String> targetWords = <String>[].obs;
  final RxList<String> committedWordBuffers = <String>[].obs;
  final RxString currentWordBuffer = ''.obs;

  int improvedCount = 0;

  void _start() {
    _clock.stop();
    _engine = TypingEngine(
      targetText: args.content,
      duration: null,
      onUpdate: _onEngineUpdate,
    );
    _refreshFromEngine();
    phase.value = MistakePracticePhase.practice;
    engine.start();
    _startTicker();
    _requestFocusNextFrame();
  }

  void restart() => _start();

  void togglePauseResume() {
    if (_engine == null) return;
    if (engine.status == TypingTestStatus.running) {
      engine.pause();
      _clock.stop();
    } else if (engine.status == TypingTestStatus.paused) {
      engine.resume();
      _startTicker();
    }
    _refreshFromEngine();
    _requestFocusNextFrame();
  }

  void onCharacter(String character) =>
      TypingInput.character(_engine, character);

  void onSpace() => TypingInput.space(_engine);

  void onBackspace() => TypingInput.backspace(_engine);

  void _startTicker() => _clock.start();

  void _onEngineUpdate() {
    _refreshFromEngine();
    if (engine.status == TypingTestStatus.completed) {
      _clock.stop();
      _computeImproved();
      phase.value = MistakePracticePhase.result;
    }
  }

  /// A weak character counts as "improved this attempt" if it appears in
  /// the drill and was never mistyped during this run — a simple,
  /// honest, current-attempt-only signal (no fake historical claim).
  void _computeImproved() {
    if (args.practicedCharacters.isEmpty) {
      improvedCount = 0;
      return;
    }
    final Set<String> mistakenThisAttempt = engine.mistakes
        .where((m) => !m.isSkippedWord && !m.isWrongWord)
        .map((m) => m.expectedCharacter.toLowerCase())
        .toSet();
    improvedCount = args.practicedCharacters
        .where((c) => !mistakenThisAttempt.contains(c.toLowerCase()))
        .length;
  }

  void _refreshFromEngine() {
    final TypingEngine e = engine;
    snapshot.value = e.snapshot;
    wordStatuses.value = e.wordStatuses;
    targetWords.value = e.targetWords;
    committedWordBuffers.value = e.committedWordBuffers;
    currentWordBuffer.value = e.currentWordBuffer;
  }

  void _requestFocusNextFrame() {
    // Settings > Auto Focus: when off, the user clicks the text area.
    if (SettingsController.currentOrNull?.autoFocus == false) return;
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (!focusNode.hasFocus) focusNode.requestFocus();
    });
  }

  @override
  void onClose() {
    _clock.stop();
    focusNode.dispose();
    super.onClose();
  }
}
