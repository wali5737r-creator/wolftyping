import 'dart:convert';

import 'mock_question.dart';

/// One teacher-created custom MCQ set: a name plus its questions.
///
/// User-created, practice-only material — never an official paper and
/// never tied to any source. Sets are saved on the device (see
/// `CustomSetsRepository`) and shared as a copyable code or a file
/// (see [encode]/[decodeCustomSet]); there is no login and no server.
///
/// Sharing format: the JSON below, base64url-encoded so it pastes as a
/// single line of text. Plain JSON is also accepted on import, so a
/// hand-written or file-exported set imports the same way.
class CustomSet {
  CustomSet({
    required this.id,
    required this.name,
    required List<MockQuestion> questions,
  }) : questions = List<MockQuestion>.unmodifiable(questions);

  /// Stable identifier, e.g. 'custom-1730000000000000'. Generated by
  /// the repository when a set is created or imported with a clash.
  final String id;

  /// Teacher-chosen display name, shown wherever the set is listed or run.
  final String name;

  final List<MockQuestion> questions;

  int get questionCount => questions.length;

  CustomSet copyWith({String? id, String? name, List<MockQuestion>? questions}) {
    return CustomSet(
      id: id ?? this.id,
      name: name ?? this.name,
      questions: questions ?? this.questions,
    );
  }

  Map<String, dynamic> toJson() {
    return <String, dynamic>{
      'version': 1,
      'id': id,
      'name': name,
      'questions': questions.map((q) => q.toJson()).toList(),
    };
  }

  /// Parses [toJson] output and validates the result (see [validate]).
  /// Throws a [FormatException] with a readable message for bad data.
  factory CustomSet.fromJson(Map<String, dynamic> json) {
    final Object? rawQuestions = json['questions'];
    if (rawQuestions is! List) {
      throw const FormatException(
        'Custom test is missing its questions list.',
      );
    }
    final CustomSet set = CustomSet(
      id: json['id'] as String? ?? '',
      name: json['name'] as String? ?? '',
      questions: rawQuestions.map((e) {
        if (e is! Map) {
          throw const FormatException(
            'Custom test contains a question that is not an object.',
          );
        }
        return MockQuestion.fromJson(
          Map<String, dynamic>.from(e),
        );
      }).toList(),
    );
    validate(set);
    return set;
  }

  /// Validates a set: non-empty name, at least one question, and every
  /// question with exactly 4 non-empty options, a correct index of
  /// 0-3, and non-empty question text. Throws [FormatException] with
  /// a readable message; never crashes the caller.
  static void validate(CustomSet set) {
    if (set.id.trim().isEmpty) {
      throw const FormatException('Custom test is missing an id.');
    }
    if (set.name.trim().isEmpty) {
      throw const FormatException('Custom test has no name.');
    }
    if (set.questions.isEmpty) {
      throw FormatException(
        'Custom test "${set.name}" has no questions.',
      );
    }
    for (final MockQuestion q in set.questions) {
      if (q.id.trim().isEmpty) {
        throw FormatException(
          'A question in "${set.name}" is missing an id.',
        );
      }
      if (q.question.trim().isEmpty) {
        throw FormatException(
          'A question in "${set.name}" has no question text.',
        );
      }
      if (q.options.length != 4) {
        throw FormatException(
          'Question "${q.id}" must have exactly 4 options '
          '(found ${q.options.length}).',
        );
      }
      for (final String option in q.options) {
        if (option.trim().isEmpty) {
          throw FormatException(
            'Question "${q.id}" has an empty option.',
          );
        }
      }
      if (q.correctIndex < 0 || q.correctIndex > 3) {
        throw FormatException(
          'Question "${q.id}" correctIndex must be 0-3 '
          '(found ${q.correctIndex}).',
        );
      }
    }
    final Set<String> ids = <String>{};
    for (final MockQuestion q in set.questions) {
      if (!ids.add(q.id)) {
        throw FormatException(
          'Custom test "${set.name}" has two questions with id "${q.id}".',
        );
      }
    }
  }

  /// Encodes this set as a single-line shareable code.
  String encode() {
    return base64Url.encode(utf8.encode(jsonEncode(toJson())));
  }

  /// Decodes a code produced by [encode], or a plain JSON object with
  /// the same shape (as produced by file export). Throws a
  /// [FormatException] with a readable message for anything else, so
  /// the import UI can show it instead of crashing.
  static CustomSet decode(String code) {
    final String trimmed = code.trim();
    if (trimmed.isEmpty) {
      throw const FormatException('Nothing to import — the code is empty.');
    }
    try {
      final Object? parsed;
      if (trimmed.startsWith('{')) {
        parsed = jsonDecode(trimmed);
      } else {
        parsed = jsonDecode(utf8.decode(base64Url.decode(trimmed)));
      }
      if (parsed is! Map) {
        throw const FormatException('Imported data is not a custom test.');
      }
      return CustomSet.fromJson(Map<String, dynamic>.from(parsed));
    } on FormatException {
      rethrow;
    } catch (e) {
      throw FormatException(
        'Could not read this custom test code. Check that the whole '
        'code was pasted, then try again. ($e)',
      );
    }
  }
}
